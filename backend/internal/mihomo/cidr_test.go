func TestParseRangesDropsUnparsable(t *testing.T) {
	got := ParseRanges("10.0.0.0/8", "nope", "", "1.2.3.4/33", "::1")
	if len(got) != 2 || got[0].Family != 4 || got[1].Family != 6 {
		t.Fatalf("ParseRanges kept %d items: %+v", len(got), got)
	}
}
